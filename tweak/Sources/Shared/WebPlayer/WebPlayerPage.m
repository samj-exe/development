#import <Foundation/Foundation.h>
#import "SGWebPlayerBridge.h"

NSString *SGWebPlayerPageHTML(void) {
    return
        @"<!doctype html>\n"
        @"<html lang=\"en\"><head><meta charset=\"utf-8\">\n"
        @"<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">\n"
        @"<meta name=\"referrer\" content=\"no-referrer\"><title>Browser player</title>\n"
        @"<style>\n"
        @":root{color-scheme:dark}*{box-sizing:border-box;margin:0}[hidden]{display:none!important}\n"
        @"body{background:#080808;color:#fff;font:16px -apple-system,BlinkMacSystemFont,sans-serif;padding:2.2rem 1.4rem 4rem;min-height:100vh;-webkit-font-smoothing:antialiased}\n"
        @"main{max-width:680px;margin:auto}header{color:#a2a2a2;font-size:.85rem;margin-bottom:2rem;display:flex;justify-content:space-between;gap:1rem}\n"
        @"#status{color:#aaa;padding:.7rem 0;min-height:3rem}#title{font-size:clamp(1.8rem,6vw,2.8rem);font-weight:700;line-height:1.15;overflow-wrap:anywhere}#artist{color:#aaa;margin-top:.5rem}\n"
        @"#artwork{position:relative;width:min(100%,360px);aspect-ratio:1;margin:0 auto 2rem;border-radius:16px;overflow:hidden;background:#161616}#cover,#motion{position:absolute;inset:0;width:100%;height:100%;object-fit:contain}#motion{background:#080808}#progress{background:#292929;border-radius:4px;height:6px;margin-top:1.6rem}#fill{background:#fff;border-radius:4px;height:6px;width:0}\n"
        @"#times{display:flex;justify-content:space-between;color:#aaa;font-size:.8rem;margin-top:.5rem}\n"
        @"#controls{display:flex;gap:1.2rem;align-items:center;justify-content:center;margin-top:1.5rem}button{background:#202020;border:1px solid #404040;border-radius:50%;color:#fff;width:52px;height:52px;font-size:1.3rem;cursor:pointer}button:focus-visible{outline:3px solid #fff;outline-offset:5px}button:disabled{opacity:.4}button.primary{width:64px;height:64px;background:#fff;color:#000}\n"
        @"#lyrics{margin-top:3rem;display:flex;flex-direction:column;gap:1.4rem;padding-bottom:2rem}.line{color:#888;font-size:clamp(1.5rem,5vw,2.2rem);font-weight:650;line-height:1.35;overflow-wrap:anywhere;transition:color .2s}.line.now{color:white}.line.past{color:#777}.word{opacity:.75}.word.on,.word.mid{opacity:1}.translation{font-size:.65em;font-weight:400;color:#aaa;margin-top:.35rem}\n"
        @"#lyricStatus{color:#aaa;margin-top:2rem}details{border-top:1px solid #333;margin-top:2rem;padding-top:1rem;color:#aaa}summary{cursor:pointer}#queue{padding:1rem 0 0 1.5rem}#queue li{padding:.5rem 0;overflow-wrap:anywhere}\n"
        @"@media(hover:hover){button:hover{filter:brightness(1.2)}}\n"
        @"@media(prefers-reduced-motion:reduce){*{scroll-behavior:auto!important;transition:none!important}}\n"
        @"</style></head><body><main>\n"
        @"<header><span>Browser player</span><span>Sound plays on iPhone</span></header>\n"
        @"<p id=\"status\" role=\"status\">Connecting to iPhone…</p>\n"
        @"<section id=\"card\" hidden><div id=\"artwork\" hidden><img id=\"cover\" crossorigin=\"anonymous\" referrerpolicy=\"no-referrer\" alt=\"\"><video id=\"motion\" muted autoplay playsinline loop hidden preload=\"metadata\"></video></div><h1 id=\"title\" dir=\"auto\"></h1><p id=\"artist\" dir=\"auto\"></p>\n"
        @"<div id=\"progress\"><div id=\"fill\"></div></div><div id=\"times\"><span id=\"t0\"></span><span id=\"t1\"></span></div>\n"
        @"<div id=\"controls\" hidden><button id=\"prev\" aria-label=\"Previous track\"></button><button id=\"play\" class=\"primary\" aria-label=\"Play or pause\"></button><button id=\"next\" aria-label=\"Next track\"></button></div></section>\n"
        @"<p id=\"lyricStatus\"></p><section id=\"lyrics\" aria-label=\"Lyrics\"></section>\n"
        @"<details id=\"upcoming\" hidden><summary>Up next</summary><ol id=\"queue\"></ol></details>\n"
        @"</main><script>\n"
        @"'use strict';\n"
        @"const token = location.hash.slice(1);\n"
        @"if (token) history.replaceState(null, '', location.pathname + location.search);\n"
        @"const ids = ['status','card','artwork','cover','motion','title','artist','fill','t0','t1','controls','prev','play','next','lyrics','lyricStatus','upcoming','queue'];\n"
        @"const els = Object.fromEntries(ids.map(id => [id, document.getElementById(id)]));\n"
        @"let snap = null, snapAt = 0, lineKey = '', queueKey = '', built = [], lastScrolled = -1, fetching = false, expired = false, posting = false;\n"
        @"let mediaKey = '', mediaURL = '', mediaAbort = null, mediaGeneration = 0, coverKey = '';\n"
        @"const reduced = matchMedia('(prefers-reduced-motion: reduce)');\n"
        @"function setIcon(button, name) {\n"
        @"  const paths = {play:'M7 3v18l14-9z',pause:'M5 3h5v18H5zm9 0h5v18h-5z',previous:'M4 3h3v18H4zm16 0L7 12l13 9z',next:'M17 3h3v18h-3zM4 3v18l13-9z'};\n"
        @"  const svg = document.createElementNS('http://www.w3.org/2000/svg','svg'), path = document.createElementNS('http://www.w3.org/2000/svg','path');\n"
        @"  svg.setAttribute('viewBox','0 0 24 24'); svg.setAttribute('width','22'); svg.setAttribute('height','22'); svg.setAttribute('aria-hidden','true');\n"
        @"  path.setAttribute('d',paths[name]); path.setAttribute('fill','currentColor'); svg.appendChild(path); button.replaceChildren(svg);\n"
        @"}\n"
        @"setIcon(els.prev,'previous'); setIcon(els.next,'next');\n"
        @"function fmt(ms) { if (!Number.isFinite(ms) || ms < 0) return ''; const s = Math.floor(ms / 1000); return Math.floor(s / 60) + ':' + String(s % 60).padStart(2, '0'); }\n"
        @"function positionNow() {\n"
        @"  if (!snap || !Number.isFinite(snap.positionMs) || snap.positionMs < 0) return null;\n"
        @"  const dt = snap.paused ? 0 : Math.min(2000, Math.max(0, performance.now() - snapAt)) * (snap.speed || 1);\n"
        @"  const p = snap.positionMs + dt;\n"
        @"  return snap.durationMs > 0 ? Math.min(p, snap.durationMs) : p;\n"
        @"}\n"
        @"function clear() { releaseMedia(); els.cover.removeAttribute('src'); els.artwork.hidden = true; coverKey = ''; snap = null; built = []; lineKey = ''; queueKey = ''; els.card.hidden = true; els.controls.hidden = true; els.upcoming.hidden = true; els.lyrics.textContent = ''; els.lyricStatus.textContent = ''; }\n"
        @"function buildLines(lines) {\n"
        @"  built = []; els.lyrics.textContent = ''; lastScrolled = -1;\n"
        @"  for (const line of lines) {\n"
        @"    const row = document.createElement('div'); row.className = 'line'; row.dir = 'auto';\n"
        @"    const words = [];\n"
        @"    if (line.words && line.words.length) {\n"
        @"      line.words.forEach((word, i) => {\n"
        @"        if (i && !word.joined) row.appendChild(document.createTextNode(' '));\n"
        @"        const span = document.createElement('span'); span.className = 'word'; span.textContent = word.t || '';\n"
        @"        row.appendChild(span); words.push({el:span,s:word.s,e:word.e});\n"
        @"      });\n"
        @"    } else row.textContent = line.text || '';\n"
        @"    if (line.translation) { const tr = document.createElement('div'); tr.className = 'translation'; tr.dir = 'auto'; tr.textContent = line.translation; row.appendChild(tr); }\n"
        @"    els.lyrics.appendChild(row); built.push({el:row,line,words});\n"
        @"  }\n"
        @"}\n"
        @"function paint() {\n"
        @"  pauseMediaIfNeeded();\n"
        @"  if (document.hidden || !snap || !snap.ok) return;\n"
        @"  const p = positionNow();\n"
        @"  els.t0.textContent = fmt(p); els.t1.textContent = fmt(snap.durationMs);\n"
        @"  els.fill.style.width = p !== null && snap.durationMs > 0 ? Math.max(0, Math.min(100, p * 100 / snap.durationMs)) + '%' : '0%';\n"
        @"  if (p === null) return;\n"
        @"  let active = -1;\n"
        @"  const lyricP = p + (snap.lyricsDelayMs || 0);\n"
        @"  built.forEach((item, i) => {\n"
        @"    const line = item.line, end = line.e > line.s ? line.e : (built[i + 1] ? built[i + 1].line.s : snap.durationMs);\n"
        @"    const timed = line.timing !== 2;\n"
        @"    const now = timed && lyricP >= line.s && lyricP < end;\n"
        @"    item.el.className = !timed ? 'line now' : now ? 'line now' : lyricP >= end ? 'line past' : 'line';\n"
        @"    if (active < 0 && now) active = i;\n"
        @"    item.words.forEach(w => { w.el.className = !timed || lyricP >= w.e && w.e > w.s ? 'word on' : lyricP >= w.s ? 'word mid' : 'word'; });\n"
        @"  });\n"
        @"  if (active >= 0 && active !== lastScrolled) {\n"
        @"    lastScrolled = active;\n"
        @"    window.scrollTo({top:Math.max(0, built[active].el.getBoundingClientRect().top + window.scrollY - window.innerHeight * .42),behavior:reduced.matches ? 'auto' : 'smooth'});\n"
        @"  }\n"
        @"}\n"
        @"function releaseMedia() {\n"
        @"  ++mediaGeneration;\n"
        @"  if (mediaAbort) mediaAbort.abort(); mediaAbort = null; mediaKey = '';\n"
        @"  els.motion.pause(); els.motion.removeAttribute('src'); els.motion.load(); els.motion.hidden = true;\n"
        @"  if (mediaURL) URL.revokeObjectURL(mediaURL); mediaURL = '';\n"
        @"}\n"
        @"function pauseMediaIfNeeded() {\n"
        @"  if (document.hidden || !snap || snap.paused || performance.now() - snapAt > 4000) els.motion.pause();\n"
        @"  else if (mediaURL && els.motion.paused && !els.motion.hidden) els.motion.play().catch(error => { if (error.name !== 'AbortError' && !document.hidden && snap && !snap.paused) els.motion.hidden = true; });\n"
        @"}\n"
        @"async function loadMedia(media, key) {\n"
        @"  const generation = mediaGeneration, controller = new AbortController(); mediaAbort = controller;\n"
        @"  try {\n"
        @"    const chunks = [];\n"
        @"    for (let start = 0; start < media.bytes; start += 262144) {\n"
        @"      if (generation !== mediaGeneration || document.hidden) throw new Error('Outdated media');\n"
        @"      const end = Math.min(media.bytes - 1, start + 262143);\n"
        @"      const res = await request(media.path, {headers:{Range:'bytes=' + start + '-' + end}, signal:controller.signal});\n"
        @"      if (res.status !== 206 || res.headers.get('Content-Range') !== 'bytes ' + start + '-' + end + '/' + media.bytes || res.headers.get('Content-Type') !== 'video/mp4') throw new Error('Unavailable media');\n"
        @"      const chunk = await res.arrayBuffer();\n"
        @"      if (chunk.byteLength !== end - start + 1) throw new Error('Bad media size');\n"
        @"      chunks.push(chunk);\n"
        @"    }\n"
        @"    if (generation !== mediaGeneration || !snap || mediaKey !== key) return;\n"
        @"    mediaURL = URL.createObjectURL(new Blob(chunks, {type:'video/mp4'}));\n"
        @"    els.motion.muted = true; els.motion.src = mediaURL; els.motion.hidden = false; els.artwork.hidden = false;\n"
        @"    pauseMediaIfNeeded();\n"
        @"  } catch (_) {\n"
        @"    if (generation === mediaGeneration) { els.motion.hidden = true; if (!els.cover.getAttribute('src')) els.artwork.hidden = true; }\n"
        @"  } finally { if (mediaAbort === controller) mediaAbort = null; }\n"
        @"}\n"
        @"function renderArtwork() {\n"
        @"  const cover = typeof snap.cover === 'string' && /^https:\\/\\/i\\.scdn\\.co\\/image\\/[a-fA-F0-9]{32,128}$/.test(snap.cover) ? snap.cover : '';\n"
        @"  if (cover !== coverKey) {\n"
        @"    coverKey = cover; els.cover.hidden = !cover;\n"
        @"    if (cover) { els.cover.alt = (snap.track.title || 'Track') + ' cover'; els.cover.src = cover; } else els.cover.removeAttribute('src');\n"
        @"  }\n"
        @"  const media = snap.motion;\n"
        @"  const valid = media && /^[A-Fa-f0-9-]{36}$/.test(media.id || '') && media.path === '/api/artwork/' + media.id && Number.isInteger(media.bytes) && media.bytes >= 12 && media.bytes <= 16777216;\n"
        @"  const key = valid && !document.hidden ? snap.track.id + ':' + media.id : '';\n"
        @"  if (key !== mediaKey) { releaseMedia(); mediaKey = key; if (valid && !document.hidden) loadMedia(media,key); }\n"
        @"  els.artwork.hidden = (!cover || els.cover.hidden) && (!mediaURL || els.motion.hidden);\n"
        @"  pauseMediaIfNeeded();\n"
        @"}\n"
        @"els.cover.addEventListener('error', () => { els.cover.hidden = true; if (!mediaURL) els.artwork.hidden = true; });\n"
        @"els.motion.addEventListener('error', () => { els.motion.hidden = true; if (!coverKey || els.cover.hidden) els.artwork.hidden = true; });\n"
        @"function render() {\n"
        @"  if (!snap || !snap.ok || !snap.track) { clear(); els.status.textContent = 'Nothing playing on the iPhone right now.'; return; }\n"
        @"  els.card.hidden = false; renderArtwork(); els.title.textContent = snap.track.title || ''; els.artist.textContent = snap.track.artist || '';\n"
        @"  els.status.textContent = snap.paused ? 'Paused on iPhone' : '';\n"
        @"  els.controls.hidden = !snap.controls; setIcon(els.play, snap.paused ? 'play' : 'pause'); els.play.setAttribute('aria-label', snap.paused ? 'Play' : 'Pause');\n"
        @"  const lines = snap.lines || [], nextKey = snap.track.id + JSON.stringify(lines);\n"
        @"  if (nextKey !== lineKey) { lineKey = nextKey; buildLines(lines); }\n"
        @"  els.lyricStatus.textContent = snap.truncated ? 'Lyrics shortened for this browser mirror.' : lines.length ? '' : snap.looking ? 'Looking for lyrics…' : 'No lyrics available for this track.';\n"
        @"  const queue = snap.queue || [], nextQueueKey = JSON.stringify(queue);\n"
        @"  if (nextQueueKey !== queueKey) { queueKey = nextQueueKey; els.queue.textContent = ''; for (const track of queue) { const li = document.createElement('li'); li.dir = 'auto'; li.textContent = (track.title || '') + (track.artist ? ' · ' + track.artist : ''); els.queue.appendChild(li); } }\n"
        @"  els.upcoming.hidden = !queue.length; paint();\n"
        @"}\n"
        @"async function request(path, options) {\n"
        @"  const controller = new AbortController(), outer = options && options.signal;\n"
        @"  const abort = () => controller.abort();\n"
        @"  if (outer) { if (outer.aborted) controller.abort(); else outer.addEventListener('abort',abort,{once:true}); }\n"
        @"  const timer = setTimeout(abort, 4000);\n"
        @"  try {\n"
        @"    const response = await fetch(path, {...options, cache:'no-store', credentials:'omit', signal:controller.signal, headers:{Authorization:'Bearer ' + token, ...(options && options.headers)}});\n"
        @"    const reader = response.body.getReader(), parts = []; let total = 0;\n"
        @"    for (;;) { const piece = await reader.read(); if (piece.done) break; total += piece.value.byteLength; if (total > 524288) { await reader.cancel(); throw new Error('Response too large'); } parts.push(piece.value); }\n"
        @"    const bytes = new Uint8Array(total); let offset = 0; for (const part of parts) { bytes.set(part,offset); offset += part.byteLength; }\n"
        @"    return new Response(bytes,{status:response.status,headers:response.headers});\n"
        @"  } finally { clearTimeout(timer); if (outer) outer.removeEventListener('abort',abort); }\n"
        @"}\n"
        @"async function poll() {\n"
        @"  if (expired || fetching) return;\n"
        @"  if (!token) { clear(); expired = true; els.status.textContent = 'Open the full link from Spotify to connect.'; return; }\n"
        @"  fetching = true;\n"
        @"  try {\n"
        @"    const res = await request('/api/state');\n"
        @"    if (res.status === 401) { clear(); expired = true; els.status.textContent = 'This link expired. Start Browser player again and open its new link.'; }\n"
        @"    else if (res.ok) { snap = await res.json(); snapAt = performance.now(); render(); }\n"
        @"    else if (res.status !== 429) throw new Error('Disconnected');\n"
        @"  } catch (_) { releaseMedia(); els.status.textContent = 'Waiting for iPhone — keep Spotify open on the same Wi-Fi.'; els.controls.hidden = true; }\n"
        @"  finally { fetching = false; }\n"
        @"}\n"
        @"async function post(action) {\n"
        @"  if (!snap || !snap.controls || !token || expired || posting) return;\n"
        @"  posting = true; [els.prev, els.play, els.next].forEach(b => b.disabled = true);\n"
        @"  try { const res = await request('/api/control', {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action})}); if (!res.ok) els.status.textContent = res.status === 403 ? 'Browser controls are off or this page is no longer allowed.' : 'Control could not be sent.'; }\n"
        @"  catch (_) { els.status.textContent = 'Could not reach iPhone.'; }\n"
        @"  finally { posting = false; [els.prev, els.play, els.next].forEach(b => b.disabled = false); }\n"
        @"  await poll();\n"
        @"}\n"
        @"els.prev.addEventListener('click', () => post('previous')); els.next.addEventListener('click', () => post('next')); els.play.addEventListener('click', () => post(snap && snap.paused ? 'play' : 'pause'));\n"
        @"document.addEventListener('visibilitychange', () => { if (document.hidden) releaseMedia(); else { if (snap) renderArtwork(); poll(); } });\n"
        @"window.addEventListener('pagehide', releaseMedia);\n"
        @"async function loop() { await poll(); if (!expired) setTimeout(loop, document.hidden ? 3000 : snap && snap.paused ? 1500 : 1000); }\n"
        @"loop(); setInterval(paint, 100);\n"
        @"</script></body></html>\n"
    ;
}
