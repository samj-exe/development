#!/usr/bin/env python3
"""Embed the reviewed browser assets in the tweak; no runtime CDN dependency."""
import argparse, json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
folder = root / 'tweak/Sources/Shared/Jam'
html = (folder/'Web/index.html').read_text().replace('/* WEBJAM_CLIENT */', (folder/'Web/client.js').read_text())
output = '// Generated by scripts/generate-webjam.py. Edit Web/index.html and Web/client.js.\n#import "WebJam.h"\n\nNSString *SGWebJamHTMLPage(void) {\n    return\n' + ''.join('        @' + json.dumps(line, ensure_ascii=False) + '\n' for line in html.splitlines(keepends=True)) + '        ;\n}\n'
parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args=parser.parse_args()
p = folder/'WebJamWeb.m'
if args.check:
    if not p.exists() or p.read_text() != output: raise SystemExit('Web Jam assets are stale: run python3 scripts/generate-webjam.py')
elif not p.exists() or p.read_text() != output:
    p.write_text(output)
